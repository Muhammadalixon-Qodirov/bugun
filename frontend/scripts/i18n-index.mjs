// Writes src/messages/<locale>/index.ts for each locale: one import per
// namespace file, so a new namespace is just a new JSON file plus this script.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../src/messages/", import.meta.url);
const locales = ["uz", "en", "ru"];

export function indexSource(locale) {
  const names = readdirSync(new URL(`${locale}/`, dir))
    .filter((f) => f.endsWith(".json"))
    .map((f) => f.slice(0, -5))
    .sort();
  const imports = names.map((n) => `import ${n} from "./${n}.json";`).join("\n");
  return `// Generated by scripts/i18n-index.mjs (npm run i18n:index). Do not edit.\n${imports}\n\nconst messages = { ${names.join(", ")} };\n\nexport default messages;\n`;
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  for (const locale of locales) {
    const file = new URL(`${locale}/index.ts`, dir);
    const next = indexSource(locale);
    let prev = "";
    try {
      prev = readFileSync(file, "utf8");
    } catch {}
    if (prev !== next) writeFileSync(file, next);
  }
  console.log("i18n index written for", locales.join(", "));
}
